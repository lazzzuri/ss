export const DICT: Record<Lang, Dict> = { uk, ru };
export type { Dict };

export function t(lang: Lang): Dict {
  return DICT[lang];
}

export function fill(s: string, vars: Record<string, string | number>): string {
  return s.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ""));
}
